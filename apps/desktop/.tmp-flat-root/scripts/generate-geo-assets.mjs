// Regenerates the two static geo assets used by the admin Traffic panel:
//   src/lib/world-land-map.ts    — precomputed Robinson land SVG path + projection
//   src/lib/country-centroids.ts — ISO 3166-1 alpha-2 → [lat, lng] centroids
//
// Run from apps/web:  pnpm generate:geo
// Runtime cost: zero polygons — the client ships one SVG path `d` string and
// reuses the same Robinson scale/translate (via d3-geo-projection) for pins.
//
// Filled path (not a hex-dot grid) preserves jagged Arctic coasts and polar
// tips that discrete sampling flattens — plain SVG `<path>`, no map library.

import { writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { geoPath } from "d3-geo"
import { geoRobinson } from "d3-geo-projection"
import { feature } from "topojson-client"

const require = createRequire(import.meta.url)
const countries = require("world-countries")
// 110m keeps polar tips / archipelagos as continuous geometry without a
// ~0.5MB client path string (50m). Jagged enough for a filled silhouette.
const landTopo = require("world-atlas/land-110m.json")

const here = dirname(fileURLToPath(import.meta.url))
const out = (name) => join(here, "..", "src", "lib", name)

/** Robinson silhouette (~1.97:1), Antarctica omitted. */
const WIDTH = 168
const HEIGHT = 85
/** Drop Antarctica — traffic maps end south of Tierra del Fuego / NZ. */
const ANTARCTICA_MAX_LAT = -55

/**
 * world-atlas `land` is a GeometryCollection → FeatureCollection of polygons.
 * Keep any polygon whose outer ring reaches north of Antarctica.
 */
function landWithoutAntarctica(topo) {
  const fc = feature(topo, topo.objects.land)
  const feats = fc.type === "FeatureCollection" ? fc.features : [fc]
  const coordinates = []
  for (const f of feats) {
    const g = f.geometry
    if (!g) continue
    const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates
    for (const poly of polys) {
      let maxLat = -90
      for (const ring of poly) {
        for (const [, lat] of ring) {
          if (lat > maxLat) maxLat = lat
        }
      }
      if (maxLat < ANTARCTICA_MAX_LAT) continue
      coordinates.push(poly)
    }
  }
  return {
    type: "Feature",
    properties: {},
    geometry: { type: "MultiPolygon", coordinates },
  }
}

const landFeature = landWithoutAntarctica(landTopo)
const projection = geoRobinson().fitExtent(
  [
    [1.8, 2.2],
    [WIDTH - 1.8, HEIGHT - 1.8],
  ],
  landFeature
)
// Slight south bias so Greenland / Ellesmere tip sits inside the frame.
projection.translate([
  projection.translate()[0],
  projection.translate()[1] + 0.7,
])

const pathGen = geoPath(projection)
const [[minX, minY], [maxX, maxY]] = pathGen.bounds(landFeature)
if (minX < 0 || minY < 0 || maxX > WIDTH || maxY > HEIGHT) {
  throw new Error(
    `land silhouette overflows viewBox ${WIDTH}×${HEIGHT}: ` +
      `bbox [${minX.toFixed(2)},${minY.toFixed(2)}]–[${maxX.toFixed(2)},${maxY.toFixed(2)}]`
  )
}

// digits(1) keeps the path compact while preserving polar tips/jagged coasts.
const landPath = pathGen.digits(1)(landFeature)
if (!landPath) {
  throw new Error("geoPath produced an empty land silhouette")
}

const [tx, ty] = projection.translate()
const mapAsset = {
  width: WIDTH,
  height: HEIGHT,
  projection: {
    name: "robinson",
    scale: Number(projection.scale().toFixed(6)),
    translate: [Number(tx.toFixed(4)), Number(ty.toFixed(4))],
  },
  path: landPath,
}

writeFileSync(
  out("world-land-map.ts"),
  `// Generated by scripts/generate-geo-assets.mjs — do not edit by hand.
export interface WorldLandMap {
  width: number
  height: number
  projection: {
    name: "robinson"
    scale: number
    translate: readonly [number, number]
  }
  /** Robinson-projected land MultiPolygon as a single SVG path \`d\`. */
  path: string
}

export const WORLD_LAND_MAP: WorldLandMap = ${JSON.stringify(mapAsset)} as const
`
)

const centroids = Object.fromEntries(
  countries
    .filter((c) => c.cca2 && c.latlng?.length === 2)
    .map((c) => [
      c.cca2,
      [Number(c.latlng[0].toFixed(2)), Number(c.latlng[1].toFixed(2))],
    ])
)
writeFileSync(
  out("country-centroids.ts"),
  `// Generated by scripts/generate-geo-assets.mjs from world-countries — do not edit by hand.
export const COUNTRY_CENTROIDS: Record<string, readonly [number, number]> = ${JSON.stringify(centroids, null, 2)}
`
)

console.log(
  `land path: ${(landPath.length / 1024).toFixed(1)} KiB, scale: ${mapAsset.projection.scale}, centroids: ${Object.keys(centroids).length}`
)
