// Regenerates the two static geo assets used by the admin Traffic panel:
//   src/lib/world-dot-map.ts     — precomputed dotted-map grid (world, diagonal)
//   src/lib/country-centroids.ts — ISO 3166-1 alpha-2 → [lat, lng] centroids
//
// Run from apps/web:  node scripts/generate-geo-assets.mjs
// Runtime cost: zero — both outputs are committed static data, so the client
// uses dotted-map/without-countries and never ships country polygons.

import { writeFileSync } from "node:fs"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"
import { getMapJSON } from "dotted-map"

const countries = createRequire(import.meta.url)("world-countries")

const here = dirname(fileURLToPath(import.meta.url))
const out = (name) => join(here, "..", "src", "lib", name)

// Height tuned for a half-width dashboard card: ~2:1 world at 48 rows keeps
// continents recognizable without bloating the committed JSON.
const mapJson = getMapJSON({ height: 48, grid: "diagonal" })
writeFileSync(
  out("world-dot-map.ts"),
  `// Generated by scripts/generate-geo-assets.mjs — do not edit by hand.
export const WORLD_DOT_MAP_JSON = ${JSON.stringify(mapJson)} as string
`
)

const centroids = Object.fromEntries(
  countries
    .filter((c) => c.cca2 && c.latlng?.length === 2)
    .map((c) => [
      c.cca2,
      [Number(c.latlng[0].toFixed(2)), Number(c.latlng[1].toFixed(2))],
    ])
)
writeFileSync(
  out("country-centroids.ts"),
  `// Generated by scripts/generate-geo-assets.mjs from world-countries — do not edit by hand.
export const COUNTRY_CENTROIDS: Record<string, readonly [number, number]> = ${JSON.stringify(centroids, null, 2)}
`
)

console.log(
  `map: ${mapJson.length} bytes, centroids: ${Object.keys(centroids).length} countries`
)
